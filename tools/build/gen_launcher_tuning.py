"""Writes the 3DS app's screen tuning (tools/build/installer_3ds/source/hf_tuning.h) from
core/game/data/curated/launcher_ui.json and the PC program's colours (core/gui/qt/theme.py), so the console's screens
look like the PC program and no tuning value is written in C.

    python tools/build/gen_launcher_tuning.py [--check]
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TUNING = ROOT / "core" / "game" / "data" / "curated" / "launcher_ui.json"
THEME = ROOT / "core" / "gui" / "qt" / "theme.py"
OUTPUT = ROOT / "tools" / "build" / "installer_3ds" / "source" / "hf_tuning.h"
COLOURS = ("BG", "CARD", "CARD_HOVER", "BORDER", "TEXT", "MUTED", "GOLD", "GOLD_HOVER", "ORANGE", "VIOLET",
           "VIOLET_DARK", "DISABLED", "DANGER")
# the JSON's keys as the header's macros, and the unit change on the way
FIELDS = (
    ("download_kib_s", "DOWNLOAD_KIB_S", 1), ("install_kib_s", "INSTALL_KIB_S", 1), ("finish_s", "FINISH_MS", 1000),
    ("finish_cap_permille", "FINISH_CAP_PERMILLE", 1), ("cancel_window_ms", "CANCEL_WINDOW_MS", 1),
    ("backlight_idle_s", "BACKLIGHT_IDLE_MS", 1000), ("battery_low_level", "BATTERY_LOW_LEVEL", 1),
    ("sd_spare_mb", "SD_SPARE_MB", 1), ("mod_title_per_set", "MOD_TITLE_PER_SET", 1), ("fps_menu", "FPS_MENU", 1),
    ("fps_task", "FPS_TASK", 1),
    ("input_hz", "INPUT_HZ", 1), ("safe_mode_frames", "SAFE_MODE_FRAMES", 1),
    ("restart_notice_s", "RESTART_NOTICE_MS", 1000),
)


def colours(theme: Path = THEME) -> dict[str, int]:
    """The theme's named colours ("NAME = \"#rrggbb\"") as 0xRRGGBB."""
    found = dict(re.findall(r'^([A-Z_]+) = "#([0-9a-fA-F]{6})"', theme.read_text(encoding="utf-8"), re.M))
    missing = [name for name in COLOURS if name not in found]
    if missing:
        raise ValueError(f"{theme}: no colour {missing}")
    return {name: int(found[name], 16) for name in COLOURS}


def render(tuning: Path = TUNING, theme: Path = THEME) -> str:
    values = json.loads(tuning.read_text(encoding="utf-8"))
    out = ["/* Generated by tools/build/gen_launcher_tuning.py from core/game/data/curated/launcher_ui.json and",
           " * core/gui/qt/theme.py; do not edit. The launcher's screen tuning and the PC program's colours",
           " *. */",
           "#ifndef HF_TUNING_H", "#define HF_TUNING_H", ""]
    for key, macro, scale in FIELDS:
        value = values[key]
        if not isinstance(value, int) or isinstance(value, bool) or value < 0:
            raise ValueError(f"{tuning}: {key} must be a whole number >= 0, not {value!r}")
        out.append(f"#define HF_TUNE_{macro} {value * scale}u")
    if not 0 < values["finish_cap_permille"] < 1000:
        raise ValueError(f"{tuning}: finish_cap_permille must be between 1 and 999")
    out += ["", "/* uimodel.h HfUiTuning, in its fields' order */",
            "#define HF_UI_TUNING_INIT {HF_TUNE_DOWNLOAD_KIB_S, HF_TUNE_INSTALL_KIB_S, HF_TUNE_FINISH_MS, "
            "HF_TUNE_FINISH_CAP_PERMILLE, \\",
            "    HF_TUNE_CANCEL_WINDOW_MS, HF_TUNE_BACKLIGHT_IDLE_MS, (int)HF_TUNE_BATTERY_LOW_LEVEL, "
            "(uint64_t)HF_TUNE_SD_SPARE_MB << 20}", "",
            "/* core/gui/qt/theme.py, 0xRRGGBB */"]
    out += [f"#define HF_RGB_{name} 0x{value:06X}u" for name, value in colours(theme).items()]
    out += ["", "#endif", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the header is not what the files give")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print(f"{OUTPUT} is stale: run python tools/build/gen_launcher_tuning.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
