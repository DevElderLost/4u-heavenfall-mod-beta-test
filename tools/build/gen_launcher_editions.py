"""Writes the 3DS app's editions table (tools/build/installer_3ds/source/hf_editions.h) from the edition files present
in this checkout: core/game/data/curated/edition.json and every editions/*/overlay/.../edition.json. An edition's
exported repository holds only its own file, so its table knows only itself. An edition without `console_release` is
left out.

    python tools/build/gen_launcher_editions.py [--check]
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EDITION_REL = Path("core") / "game" / "data" / "curated" / "edition.json"
OUTPUT = ROOT / "tools" / "build" / "installer_3ds" / "source" / "hf_editions.h"
REGIONS = ("eur", "usa")


def edition_files(root: Path = ROOT) -> list[Path]:
    """This checkout's own edition file first, then each edition's overlay file, by folder name."""
    found = [root / EDITION_REL]
    found += sorted((root / "editions").glob("*/overlay/" + EDITION_REL.as_posix())) if (root / "editions").is_dir() \
        else []
    return [path for path in found if path.is_file()]


def _c_string(text: str) -> str:
    if not text.isascii() or any(c in text for c in ('"', "\\", "\n")):
        raise ValueError(f"not plain ASCII for C: {text!r}")
    return f'"{text}"'


def ours(title: str) -> bool:
    """An edition's application id in Heavenfall's block (launcher.h, hf_title_ours: unique ids 0x69691 to 0x6969F,
    past the launcher's 0x69690): the app removes and re-installs it, so never the original MH4U's or a system
    title's."""
    try:
        value = int(title, 16)
    except (TypeError, ValueError):
        return False
    unique = (value & 0xFFFFFFFF) >> 8
    return len(title) == 16 and value >> 32 == 0x00040000 and value & 0xFF == 0 and 0x69690 < unique <= 0x6969F


def table_entry(values: dict, path: Path) -> dict | None:
    """One edition's row: slug, names, repository, title ids and release assets, or None without console_release."""
    release = values.get("console_release")
    if release is None:
        return None
    ids = (values.get("console_title") or {}).get("title_ids")
    if not ids or sorted(ids) != sorted(REGIONS):
        raise ValueError(f"{path}: console_release needs console_title with the title ids of both regions")
    for region in REGIONS:
        if not ours(ids[region]):
            raise ValueError(f"{path}: {region} title {ids[region]} is not a Heavenfall title id (0004000006969100 to "
                             "0004000006969F00): the app removes and installs it")
    slug = values["user_folder"].lstrip(".")
    if not slug or "/" in slug or any(c.isspace() for c in slug):
        raise ValueError(f"{path}: bad user_folder {values['user_folder']!r}")
    return {
        "slug": slug, "name": values["name"], "repository": values["repository"],
        "title_eur": ids["eur"].lower(), "title_usa": ids["usa"].lower(),
        "cia": release["app_cia"], "dsx": release["app_3dsx"],
        "patch_eur": release["patch_eur"], "patch_usa": release["patch_usa"],
        "patch_eur_xx": release["patch_eur_xx"], "patch_usa_xx": release["patch_usa_xx"],
    }


def render(root: Path = ROOT) -> str:
    rows = []
    for path in edition_files(root):
        row = table_entry(json.loads(path.read_text(encoding="utf-8")), path)
        if row:
            rows.append(row)
    if not rows:
        raise ValueError("no edition with console_release in this checkout")
    slugs = [row["slug"] for row in rows]
    if len(set(slugs)) != len(slugs):
        raise ValueError(f"two editions with the same folder: {slugs}")
    out = ["/* Generated by tools/build/gen_launcher_editions.py from the edition files of this checkout; do not edit.",
           " * The editions the 3DS app can update: the repository their releases are published in, their titles'",
           " * ids and the names of the release files it reads. */",
           "#ifndef HF_EDITIONS_H", "#define HF_EDITIONS_H", "",
           "#include \"hf_edition.h\"", "",
           f"#define HF_EDITION_COUNT {len(rows)}", "",
           "static const HfEdition HF_EDITIONS[HF_EDITION_COUNT] = {"]
    for row in rows:
        fields = ("slug", "name", "repository", "title_eur", "title_usa", "cia", "dsx", "patch_eur", "patch_usa",
                  "patch_eur_xx", "patch_usa_xx")
        out.append("    {" + ", ".join(_c_string(row[f]) for f in fields) + "},")
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the header is not what the files give")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print(f"{OUTPUT} is stale: run python tools/build/gen_launcher_editions.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
